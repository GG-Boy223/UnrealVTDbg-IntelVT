param(
    [string]$DistRoot = "dist\UnrealVTDbg-x64-20260613",
    [string]$ManifestName = "PACKAGE-MANIFEST.txt"
)

$ErrorActionPreference = "Stop"

function Get-RelativePath
{
    param(
        [string]$Root,
        [string]$Path
    )

    $rootFull = [System.IO.Path]::GetFullPath($Root).TrimEnd('\')
    $pathFull = [System.IO.Path]::GetFullPath($Path)
    return $pathFull.Substring($rootFull.Length + 1)
}

$rootPath = (Resolve-Path $DistRoot).Path
$manifestPath = Join-Path $rootPath $ManifestName
$files = Get-ChildItem -LiteralPath $rootPath -Recurse -File |
    Where-Object {
        $_.Name -ne $ManifestName -and
        $_.Extension -notin @(".log", ".tmp")
    } |
    Sort-Object FullName

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# UnrealVTDbg x64 package manifest")
$lines.Add("# Format: relative-path<TAB>size-bytes<TAB>SHA256:<hash>")
$lines.Add("# Generated by scripts/release/refresh_dist_manifest_x64.ps1")

foreach ($file in $files)
{
    $relativePath = Get-RelativePath -Root $rootPath -Path $file.FullName
    $hash = (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash
    $lines.Add(("{0}`t{1}`tSHA256:{2}" -f $relativePath, $file.Length, $hash))
}

[System.IO.File]::WriteAllLines($manifestPath, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Output ("manifest refreshed: {0} files" -f $files.Count)
